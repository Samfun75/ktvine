package org.samfun.ktprd.utils

/**
 * A Microsoft `DRM_RESULT` status code, as a PlayReady SOAP fault reports it.
 *
 * A rejected license request comes back with nothing but a hexadecimal status code, so this maps
 * it to the identifier Microsoft publishes for it. [message] is derived mechanically from that
 * identifier rather than being a curated description — it says what the code is called, which is
 * the part a caller can act on or search for.
 *
 * The table is held as a compact string and parsed once, rather than as 884 enum constants that
 * would sit in the published ABI for the sake of a lookup keyed on a wire value.
 */
public class DrmResult internal constructor(
    public val code: Int,
    /** Microsoft's identifier, such as `DRM_E_INVALID_LICENSE`. */
    public val name: String,
) {
    /** The identifier rendered as prose: `DRM_E_INVALID_LICENSE` becomes "invalid license". */
    public val message: String
        get() = name
            .removePrefix("DRM_E_")
            .removePrefix("DRM_S_")
            .removePrefix("DRM_")
            .lowercase()
            .replace('_', ' ')

    override fun toString(): String = "DrmResult(0x${code.toUInt().toString(16).padStart(8, '0')}, $name)"

    override fun equals(other: Any?): Boolean = other is DrmResult && code == other.code && name == other.name

    override fun hashCode(): Int = 31 * code + name.hashCode()

    public companion object {
        private val byCode: Map<Int, DrmResult> by lazy {
            TABLE.lineSequence()
                .filter { it.isNotBlank() }
                .map { line ->
                    val code = line.substring(0, 8).toUInt(16).toInt()
                    code to DrmResult(code, line.substring(9))
                }
                // Two identifiers occasionally share a code; the first one listed wins.
                .distinctBy { it.first }
                .toMap()
        }

        /** Look up a status code, or `null` when it is not one this table knows. */
        public fun fromCode(code: Int): DrmResult? = byCode[code]

        /**
         * Look up a status code written as text, with or without a `0x` prefix.
         *
         * A SOAP fault carries the code as a string, and servers are inconsistent about the
         * prefix and the letter case.
         */
        public fun fromCode(code: String): DrmResult? {
            val trimmed = code.trim().removePrefix("0x").removePrefix("0X")
            val value = trimmed.toUIntOrNull(16)?.toInt() ?: trimmed.toIntOrNull() ?: return null
            return byCode[value]
        }

