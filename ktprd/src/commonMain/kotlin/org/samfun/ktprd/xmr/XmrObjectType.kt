package org.samfun.ktprd.xmr

/**
 * The tag on an XMR object.
 *
 * Only a handful matter for extracting a content key — [CONTENT_KEY], [SIGNATURE],
 * [ECC_DEVICE_KEY] and [AUX_KEY]. The rest are policy the CDM records but does not enforce;
 * enforcement is the player's job, and claiming otherwise would be misleading.
 */
public enum class XmrObjectType(public val value: Int) {
    INVALID(0x0000),
    OUTER_CONTAINER(0x0001),
    GLOBAL_POLICY_CONTAINER(0x0002),
    MINIMUM_ENVIRONMENT(0x0003),
    PLAYBACK_POLICY_CONTAINER(0x0004),
    OUTPUT_PROTECTION(0x0005),
    UPLINK_KID(0x0006),
    ANALOG_VIDEO_OUTPUT_PROTECTION_CONTAINER(0x0007),
    ANALOG_VIDEO_OUTPUT_CONFIGURATION(0x0008),
    KEY_MATERIAL_CONTAINER(0x0009),
    CONTENT_KEY(0x000A),
    SIGNATURE(0x000B),
    SERIAL_NUMBER(0x000C),
    SETTINGS(0x000D),
    COPY_POLICY_CONTAINER(0x000E),
    ALLOW_PLAYLIST_BURN_POLICY_CONTAINER(0x000F),
    INCLUSION_LIST(0x0010),
    PRIORITY(0x0011),
    EXPIRATION(0x0012),
    ISSUE_DATE(0x0013),
    EXPIRATION_AFTER_FIRST_USE(0x0014),
    EXPIRATION_AFTER_FIRST_STORE(0x0015),
    METERING(0x0016),
    PLAY_COUNT(0x0017),
    GRACE_PERIOD(0x001A),
    COPY_COUNT(0x001B),
    COPY_PROTECTION(0x001C),
    PLAYLIST_BURN_COUNT(0x001F),
    REVOCATION_INFORMATION_VERSION(0x0020),
    RSA_DEVICE_KEY(0x0021),
    SOURCE_ID(0x0022),
    REVOCATION_CONTAINER(0x0025),
    RSA_LICENSE_GRANTER_KEY(0x0026),
    USER_ID(0x0027),
    RESTRICTED_SOURCE_ID(0x0028),
    DOMAIN_ID(0x0029),
    ECC_DEVICE_KEY(0x002A),
    GENERATION_NUMBER(0x002B),
    POLICY_METADATA(0x002C),
    OPTIMIZED_CONTENT_KEY(0x002D),
    DIGITAL_AUDIO_OUTPUT_PROTECTION_CONTAINER(0x002E),
    RINGTONE_POLICY_CONTAINER(0x002F),
    EXPIRATION_AFTER_FIRST_PLAY(0x0030),
    DIGITAL_AUDIO_OUTPUT_CONFIGURATION(0x0031),
    REVOCATION_INFORMATION_VERSION_2(0x0032),
    EMBEDDING_BEHAVIOUR(0x0033),
    SECURITY_LEVEL(0x0034),
    COPY_TO_PC_CONTAINER(0x0035),
    PLAY_ENABLER_CONTAINER(0x0036),
    MOVE_ENABLER(0x0037),
    COPY_ENABLER_CONTAINER(0x0038),
    PLAY_ENABLER(0x0039),
    COPY_ENABLER(0x003A),
    UPLINK_KID_2(0x003B),
    COPY_POLICY_2_CONTAINER(0x003C),
    COPY_COUNT_2(0x003D),
    RINGTONE_ENABLER(0x003E),
    EXECUTE_POLICY_CONTAINER(0x003F),
    EXECUTE_POLICY(0x0040),
    READ_POLICY_CONTAINER(0x0041),
    REMOVAL_DATE(0x0050),
    AUX_KEY(0x0051),
    UPLINK_X(0x0052),
    APPLICATION_ID_LIST(0x0054),
    REAL_TIME_EXPIRATION(0x0055),
    ND_TX_AUTH_CONTAINER(0x0056),
    ND_TX_AUTH(0x0057),
    DIGITAL_VIDEO_PROTECTION_CONTAINER(0x0058),
    DIGITAL_VIDEO_OPL(0x0059),
    SECURE_STOP(0x005A),
    SECURE_STOP_2(0x005C),
    OPTIMIZED_CONTENT_KEY_2(0x005D),
    UNKNOWN_OBJECT(0xFFFD),
    UNKNOWN_CONTAINER(0xFFFE),
    ;

    public companion object {
        public fun of(value: Int): XmrObjectType = entries.firstOrNull { it.value == value } ?: UNKNOWN_OBJECT
    }
}
